const std = @import("std");
const vibe_jinja = @import("vibe_jinja");
const environment = vibe_jinja.environment;
const context = vibe_jinja.context;
const value_mod = vibe_jinja.value;
const CountingAllocator = vibe_jinja.counting_allocator.CountingAllocator;

/// Fair comparison benchmark - matches Python Jinja2 benchmark methodology exactly:
/// pre-compiled template, pre-built context, per-iteration timing of render() only.
///
/// Timing uses std.time.Timer (mach absolute time on macOS, ~40ns resolution) —
/// std.time.nanoTimestamp() quantizes to ~1us on macOS and is unusable for
/// sub-10us measurements.
///
/// Python reference numbers are read from test/benchmarks/python_reference.json,
/// regenerated by `python3 test/benchmarks/benchmark_python.py` on the same
/// machine. Falls back to a stale built-in table when the file is absent.
const PythonRef = struct {
    avg_ns: f64,
    median_ns: f64 = 0,
    min_ns: f64 = 0,
};

const PythonRefs = struct {
    simple_template: ?PythonRef = null,
    loop_template: ?PythonRef = null,
    conditional: ?PythonRef = null,
    filter_chain: ?PythonRef = null,

    /// Stale fallback (2026-06 run, Apple Silicon / Python 3.13) used only when
    /// python_reference.json is missing.
    fn fallback() PythonRefs {
        return .{
            .simple_template = .{ .avg_ns = 3427 },
            .loop_template = .{ .avg_ns = 3800 },
            .conditional = .{ .avg_ns = 3211 },
            .filter_chain = .{ .avg_ns = 3771 },
        };
    }
};

const reference_path = "test/benchmarks/python_reference.json";

fn loadPythonRefs(allocator: std.mem.Allocator) PythonRefs {
    const data = std.fs.cwd().readFileAlloc(allocator, reference_path, 1 << 20) catch {
        std.debug.print("(python_reference.json not found; using stale fallback constants — run benchmark_python.py to refresh)\n\n", .{});
        return PythonRefs.fallback();
    };
    defer allocator.free(data);

    const parsed = std.json.parseFromSlice(PythonRefs, allocator, data, .{
        .ignore_unknown_fields = true,
    }) catch {
        std.debug.print("(failed to parse python_reference.json; using stale fallback constants)\n\n", .{});
        return PythonRefs.fallback();
    };
    defer parsed.deinit();
    return parsed.value;
}

const BenchStats = struct {
    avg_ns: u64,
    median_ns: u64,
    p95_ns: u64,
    min_ns: u64,
    max_ns: u64,
    allocs_per_render: u64,
    bytes_per_render: u64,
};

/// Time `iterations` render() calls (after `warmup` untimed calls), then measure
/// backing-allocator traffic per render with a counting allocator.
fn benchRender(
    compiled: *vibe_jinja.CompiledTemplate,
    ctx: *context.Context,
    allocator: std.mem.Allocator,
    iterations: usize,
    warmup: usize,
) !BenchStats {
    for (0..warmup) |_| {
        const result = try compiled.render(ctx, allocator);
        allocator.free(result);
    }

    const samples = try allocator.alloc(u64, iterations);
    defer allocator.free(samples);

    var timer = try std.time.Timer.start();
    for (samples) |*s| {
        timer.reset();
        const result = try compiled.render(ctx, allocator);
        s.* = timer.read();
        allocator.free(result);
    }

    std.mem.sort(u64, samples, {}, std.sort.asc(u64));

    var total: u64 = 0;
    for (samples) |s| total += s;

    // Allocation profile: renders against a counting wrapper (untimed).
    const alloc_probe_iters: usize = 100;
    var counting = CountingAllocator.init(allocator);
    const calloc = counting.allocator();
    for (0..alloc_probe_iters) |_| {
        const result = try compiled.render(ctx, calloc);
        calloc.free(result);
    }

    return .{
        .avg_ns = total / iterations,
        .median_ns = samples[iterations / 2],
        .p95_ns = samples[(iterations * 95) / 100],
        .min_ns = samples[0],
        .max_ns = samples[iterations - 1],
        .allocs_per_render = counting.allocation_count / alloc_probe_iters,
        .bytes_per_render = counting.total_bytes / alloc_probe_iters,
    };
}

fn printStats(stats: BenchStats, ref: ?PythonRef) void {
    const ops_per_sec = if (stats.avg_ns > 0) 1_000_000_000 / stats.avg_ns else 0;
    std.debug.print(
        "  Zig:    Avg: {d}ns | Median: {d}ns | P95: {d}ns | Min: {d}ns | Max: {d}ns | {d} ops/sec\n",
        .{ stats.avg_ns, stats.median_ns, stats.p95_ns, stats.min_ns, stats.max_ns, ops_per_sec },
    );
    std.debug.print(
        "  Allocs: {d}/render | {d} bytes/render (backing allocator)\n",
        .{ stats.allocs_per_render, stats.bytes_per_render },
    );
    if (ref) |r| {
        std.debug.print("  Python: Avg: {d:.0}ns | Median: {d:.0}ns | Min: {d:.0}ns\n", .{ r.avg_ns, r.median_ns, r.min_ns });
        if (stats.avg_ns > 0) {
            const speedup = r.avg_ns / @as(f64, @floatFromInt(stats.avg_ns));
            const verdict = if (speedup >= 1.0) "ZIG WINS" else "python wins";
            std.debug.print("  Speedup: {d:.2}x ({s})\n", .{ speedup, verdict });
        }
    }
    std.debug.print("\n", .{});
}

pub fn main() !void {
    var gpa = std.heap.GeneralPurposeAllocator(.{}){};
    defer _ = gpa.deinit();
    const allocator = gpa.allocator();

    std.debug.print("\n", .{});
    std.debug.print("╔═══════════════════════════════════════════════════════════════════╗\n", .{});
    std.debug.print("║     vibe-jinja vs Python Jinja2 - Fair Comparison                 ║\n", .{});
    std.debug.print("║     (Pre-compiled templates, render-only timing)                  ║\n", .{});
    std.debug.print("╚═══════════════════════════════════════════════════════════════════╝\n", .{});
    std.debug.print("\n", .{});

    const refs = loadPythonRefs(allocator);

    // === Simple Template ===
    {
        std.debug.print("Simple Template: Hello {{{{ name }}}}!\n", .{});
        var env = environment.Environment.init(allocator);
        defer env.deinit();

        const template = try env.fromString("Hello {{ name }}!", "simple");
        var compiled = try vibe_jinja.compiler.compile(&env, template, "simple", allocator);
        defer compiled.deinit();

        var vars = std.StringHashMap(context.Value).init(allocator);
        defer vars.deinit();
        const name_str = try allocator.dupe(u8, "World");
        defer allocator.free(name_str);
        try vars.put("name", context.Value{ .string = name_str });

        var ctx = try context.Context.init(&env, vars, "simple", allocator);
        defer ctx.deinit();

        const stats = try benchRender(&compiled, &ctx, allocator, 10_000, 200);
        printStats(stats, refs.simple_template);
    }

    // === Loop Template ===
    {
        std.debug.print("Loop Template: {{%% for item in items %}}{{{{ item }}}}{{%% endfor %}}\n", .{});
        var env = environment.Environment.init(allocator);
        defer env.deinit();

        const template = try env.fromString("{% for item in items %}{{ item }}{% endfor %}", "loop");
        var compiled = try vibe_jinja.compiler.compile(&env, template, "loop", allocator);
        defer compiled.deinit();

        var vars = std.StringHashMap(context.Value).init(allocator);
        defer vars.deinit();

        const list_ptr = try allocator.create(value_mod.List);
        list_ptr.* = value_mod.List.init(allocator);
        defer list_ptr.deinit(allocator);

        for (0..10) |i| {
            try list_ptr.append(context.Value{ .integer = @intCast(i) });
        }
        try vars.put("items", context.Value{ .list = list_ptr });

        var ctx = try context.Context.init(&env, vars, "loop", allocator);
        defer ctx.deinit();

        const stats = try benchRender(&compiled, &ctx, allocator, 5_000, 200);
        printStats(stats, refs.loop_template);
    }

    // === Conditional Template ===
    {
        std.debug.print("Conditional: {{%% if condition %}}True{{%% else %}}False{{%% endif %}}\n", .{});
        var env = environment.Environment.init(allocator);
        defer env.deinit();

        const template = try env.fromString("{% if condition %}True{% else %}False{% endif %}", "cond");
        var compiled = try vibe_jinja.compiler.compile(&env, template, "cond", allocator);
        defer compiled.deinit();

        var vars = std.StringHashMap(context.Value).init(allocator);
        defer vars.deinit();
        try vars.put("condition", context.Value{ .boolean = true });

        var ctx = try context.Context.init(&env, vars, "cond", allocator);
        defer ctx.deinit();

        const stats = try benchRender(&compiled, &ctx, allocator, 10_000, 200);
        printStats(stats, refs.conditional);
    }

    // === Filter Chain ===
    {
        std.debug.print("Filter Chain: {{{{ text|upper|lower|trim|length }}}}\n", .{});
        var env = environment.Environment.init(allocator);
        defer env.deinit();

        const template = try env.fromString("{{ text|upper|lower|trim|length }}", "filter");
        var compiled = try vibe_jinja.compiler.compile(&env, template, "filter", allocator);
        defer compiled.deinit();

        var vars = std.StringHashMap(context.Value).init(allocator);
        defer vars.deinit();
        const text_str = try allocator.dupe(u8, "  Hello World  ");
        defer allocator.free(text_str);
        try vars.put("text", context.Value{ .string = text_str });

        var ctx = try context.Context.init(&env, vars, "filter", allocator);
        defer ctx.deinit();

        const stats = try benchRender(&compiled, &ctx, allocator, 5_000, 200);
        printStats(stats, refs.filter_chain);
    }

    // Run filter fast path benchmarks
    try benchmarkFilterFastPaths(allocator);

    std.debug.print("═══════════════════════════════════════════════════════════════════\n", .{});
    std.debug.print("Note: Python reference from {s} (regenerate with benchmark_python.py)\n", .{reference_path});
    std.debug.print("═══════════════════════════════════════════════════════════════════\n", .{});
}

// === Additional Filter Benchmarks ===
fn benchmarkFilterFastPaths(allocator: std.mem.Allocator) !void {
    std.debug.print("\n─── Filter Fast Path Tests ───\n\n", .{});

    var env = environment.Environment.init(allocator);
    defer env.deinit();

    const cases = [_]struct {
        label: []const u8,
        source: []const u8,
        text: []const u8,
    }{
        .{ .label = "escape (no specials - fast path)", .source = "{{ text|escape }}", .text = "Hello World No Special Chars" },
        .{ .label = "escape (with specials - slow path)", .source = "{{ text|escape }}", .text = "<script>alert('xss');</script>" },
        .{ .label = "upper (already upper - fast path)", .source = "{{ text|upper }}", .text = "ALREADY UPPERCASE" },
        .{ .label = "upper (needs change - slow path)", .source = "{{ text|upper }}", .text = "needs to be uppercased" },
    };

    for (cases) |case| {
        const template = try env.fromString(case.source, case.label);
        var compiled = try vibe_jinja.compiler.compile(&env, template, case.label, allocator);
        defer compiled.deinit();

        var vars = std.StringHashMap(context.Value).init(allocator);
        defer vars.deinit();
        const text_str = try allocator.dupe(u8, case.text);
        defer allocator.free(text_str);
        try vars.put("text", context.Value{ .string = text_str });

        var ctx = try context.Context.init(&env, vars, "test", allocator);
        defer ctx.deinit();

        const stats = try benchRender(&compiled, &ctx, allocator, 5_000, 200);
        std.debug.print("{s}: {d}ns avg (median {d}ns, {d} allocs/render)\n", .{ case.label, stats.avg_ns, stats.median_ns, stats.allocs_per_render });
    }
}
